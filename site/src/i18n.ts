export const routeFor = (lang: Lang, path = "") => {
  const cleanPath = path.replace(/^\/+|\/+$/g, "");
  if (lang === "en") {
    return cleanPath ? `/${cleanPath}` : "/";
  }
  return `/zh${cleanPath ? `/${cleanPath}` : ""}`;
};

